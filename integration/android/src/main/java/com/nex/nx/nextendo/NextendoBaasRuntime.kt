package com.nex.nx.nextendo

import kotlinx.serialization.json.JsonElement

/**
 * Owns the boundary between a server-issued nx2. credential and Eden's ACC
 * id-token cache. No signer is installed by default: a provisioned NEX
 * BAAS signing provider must be supplied before any JWT can reach the guest.
 */
internal interface NextendoBaasProvisioningProvider {
    val signer: NextendoBaasSigner

    /** Supplies the NEX-registered iss/aud/sub/hm and other server-required claims. */
    fun claimsFor(session: NextendoSessionStore.Session): Map<String, JsonElement>
}

internal object NextendoBaasRuntime {
    @Volatile
    private var provisioningProvider: NextendoBaasProvisioningProvider? = null

    @Volatile
    var diagnostic: String = "signer_not_provisioned"
        private set

    /** Public-only JWK Set for manual inspection or direct operator registration. */
    fun exportAndroidKeystorePublicJwks(): String =
        NextendoAndroidKeystoreBaasSigner.exportOrCreatePublicJwks()

    /**
     * Support-ready JSON containing the NEX app identity and public-only JWK.
     * Copying this request does not publish/register the key with Nextendo.
     */
    fun exportAndroidKeystoreRegistrationRequest(): String =
        NextendoAndroidKeystoreBaasSigner.exportOrCreateRegistrationRequest()

    /**
     * Fetches the operator-configured HTTPS jku and verifies that it serves
     * the exact kid/modulus/exponent generated by this installation.
     *
     * The returned proof is not a server acceptance receipt. It only proves
     * that this public key is reachable at the configured JWKS URL.
     */
    fun verifyAndroidKeystoreJwksPublication(
        jwksUrl: String
    ): NextendoBaasJwksVerifier.VerifiedRegistration {
        val signer = NextendoAndroidKeystoreBaasSigner.createOrLoad(jwksUrl)
        return try {
            NextendoBaasJwksVerifier.fetchAndVerify(jwksUrl, signer.publicJwk).also {
                diagnostic = "jwks_publication_verified_waiting_for_claim_contract"
            }
        } catch (error: Exception) {
            // If a previously installed key no longer matches what the server
            // publishes, remove it from ACC rather than keep signing stale tokens.
            provisioningProvider = null
            clearCache("jwks_publication_not_verified")
            throw error
        }
    }

    /**
     * Installs the signer only when the caller has the verified publication
     * proof and the issuer/audience/subject contract confirmed by Nextendo.
     */
    fun installAndroidKeystoreProvider(
        verifiedRegistration: NextendoBaasJwksVerifier.VerifiedRegistration,
        issuer: String,
        audience: String,
        subjectForSession: (NextendoSessionStore.Session) -> String,
        idTokenLifetimeSeconds: Long
    ) {
        val provider = NextendoAndroidKeystoreBaasProvider.createAfterVerifiedJwksPublication(
            registration = verifiedRegistration,
            issuer = issuer,
            audience = audience,
            subjectForSession = subjectForSession,
            idTokenLifetimeSeconds = idTokenLifetimeSeconds
        )
        provisioningProvider = provider
        diagnostic = "signer_installed_waiting_for_game_token"
    }

    /**
     * Convenience path for future provisioning code: verifies publication
     * immediately before installing the provider. Must run off the UI thread.
     */
    fun verifyAndInstallAndroidKeystoreProvider(
        jwksUrl: String,
        issuer: String,
        audience: String,
        subjectForSession: (NextendoSessionStore.Session) -> String,
        idTokenLifetimeSeconds: Long
    ) {
        val verified = verifyAndroidKeystoreJwksPublication(jwksUrl)
        installAndroidKeystoreProvider(
            verifiedRegistration = verified,
            issuer = issuer,
            audience = audience,
            subjectForSession = subjectForSession,
            idTokenLifetimeSeconds = idTokenLifetimeSeconds
        )
    }

    fun removeProvider() {
        provisioningProvider = null
        clearCache("signer_not_provisioned")
    }

    fun refresh(session: NextendoSessionStore.Session?) {
        if (session == null) {
            clearCache("account_not_connected")
            return
        }
        val now = System.currentTimeMillis() / 1000L
        if (!session.nexGameToken.startsWith("nx2.") ||
            session.nexGameToken.length <= 4 ||
            session.nexGameTokenExpiresAtEpochSeconds <= now
        ) {
            clearCache("game_token_unavailable_or_expired")
            return
        }

        val provider = provisioningProvider
        if (provider == null) {
            clearCache("signer_not_provisioned")
            return
        }

        runCatching {
            val jwt = NextendoBaasIdTokenBuilder.build(
                claims = provider.claimsFor(session),
                gameToken = session.nexGameToken,
                signer = provider.signer
            )
            // Validate the exact AuthenticationInfo/DataHolder contract before
            // making the compact JWT visible through ACC's LoadIdTokenCache.
            NextendoBaasAuthenticationInfo.encodeLoginExtraData(
                idToken = jwt,
                expectedGameToken = session.nexGameToken
            )
            NextendoNativeBridge.updateBaasIdToken(jwt)
        }.onSuccess {
            diagnostic = "baas_id_token_cached"
        }.onFailure {
            NextendoNativeBridge.clearBaasIdToken()
            diagnostic = when (it) {
                is IllegalArgumentException -> "baas_provisioning_invalid"
                else -> "baas_signing_failed"
            }
        }
    }

    fun clear() = clearCache("account_not_connected")

    private fun clearCache(reason: String) {
        NextendoNativeBridge.clearBaasIdToken()
        diagnostic = reason
    }
}
