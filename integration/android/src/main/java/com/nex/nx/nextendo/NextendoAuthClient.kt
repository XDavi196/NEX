package com.nex.nx.nextendo

import android.net.Uri
import android.util.Base64
import org.json.JSONObject
import java.io.ByteArrayOutputStream
import java.net.HttpURLConnection
import java.net.URL
import java.net.URLEncoder
import java.nio.charset.StandardCharsets
import java.security.MessageDigest
import java.security.SecureRandom

/**
 * First-party Nextendo OAuth client for NEX.
 *
 * This is a public Android client: PKCE is mandatory and no client secret is used.
 * Network calls are synchronous by design; callers must run them on Dispatchers.IO
 * or another background executor.
 */
object NextendoAuthClient {
    const val CLIENT_ID = "nxc_yAdR-14bOEq7"
    const val REDIRECT_URI = "com.nex.nx://oauth/callback"

    private const val BASE_URL = "https://nextendo.network"
    private const val AUTHORIZE_URL = "$BASE_URL/api/oauth/authorize"
    private const val TOKEN_URL = "$BASE_URL/api/oauth/token"
    private const val NEX_TOKEN_URL = "$BASE_URL/api/nex-token"

    const val SCOPES = "identity friends presence profil game.matchmaking"

    data class PendingAuthorization(
        val codeVerifier: String,
        val state: String,
        val authorizationUri: Uri
    )

    data class OAuthTokens(
        val accessToken: String,
        val refreshToken: String,
        val expiresAtEpochSeconds: Long
    )

    data class NexGameToken(
        val token: String,
        val expiresAtEpochSeconds: Long,
        val pid: Long,
        val username: String,
        val friendCode: String
    )

    class NextendoException(
        val httpStatus: Int,
        message: String
    ) : Exception(message)

    /**
     * Builds the browser authorization request. The caller opens authorizationUri
     * with a Custom Tab or the system browser and retains the returned object until
     * the callback arrives.
     */
    fun beginAuthorization(): PendingAuthorization {
        val verifier = base64Url(randomBytes(32))
        val challenge = base64Url(
            MessageDigest.getInstance("SHA-256")
                .digest(verifier.toByteArray(StandardCharsets.US_ASCII))
        )
        val state = base64Url(randomBytes(24))

        val uri = Uri.parse(AUTHORIZE_URL).buildUpon()
            .appendQueryParameter("response_type", "code")
            .appendQueryParameter("client_id", CLIENT_ID)
            .appendQueryParameter("redirect_uri", REDIRECT_URI)
            .appendQueryParameter("scope", SCOPES)
            .appendQueryParameter("state", state)
            .appendQueryParameter("code_challenge", challenge)
            .appendQueryParameter("code_challenge_method", "S256")
            .build()

        return PendingAuthorization(verifier, state, uri)
    }

    /**
     * Exchanges a one-time authorization code. A callback is rejected unless its
     * state exactly matches the value generated by beginAuthorization().
     */
    fun exchangeAuthorizationCode(
        code: String,
        returnedState: String?,
        pending: PendingAuthorization
    ): OAuthTokens {
        require(code.isNotBlank()) { "Nextendo returned an empty authorization code." }
        require(!returnedState.isNullOrBlank()) { "Nextendo callback did not contain state." }

        val expected = pending.state.toByteArray(StandardCharsets.UTF_8)
        val actual = returnedState.toByteArray(StandardCharsets.UTF_8)
        require(MessageDigest.isEqual(expected, actual)) {
            "Nextendo OAuth state validation failed."
        }

        val response = postForm(
            TOKEN_URL,
            mapOf(
                "grant_type" to "authorization_code",
                "client_id" to CLIENT_ID,
                "code" to code,
                "redirect_uri" to REDIRECT_URI,
                "code_verifier" to pending.codeVerifier
            )
        )
        return parseOAuthTokens(response)
    }

    /**
     * Refreshes the OAuth access token. The returned refresh token may rotate;
     * callers must persist the entire new token response immediately.
     */
    fun refreshAccessToken(refreshToken: String): OAuthTokens {
        require(refreshToken.isNotBlank()) { "No Nextendo refresh token is stored." }

        val response = postForm(
            TOKEN_URL,
            mapOf(
                "grant_type" to "refresh_token",
                "client_id" to CLIENT_ID,
                "refresh_token" to refreshToken
            )
        )
        return parseOAuthTokens(response)
    }

    /**
     * Exchanges the OAuth account token for the distinct NEX game credential.
     * The OAuth access token itself must never be placed in a game's nnex claim.
     */
    fun fetchNexGameToken(accessToken: String): NexGameToken {
        require(accessToken.isNotBlank()) { "No Nextendo access token is available." }

        val response = request(
            url = NEX_TOKEN_URL,
            method = "GET",
            headers = mapOf("Authorization" to "Bearer $accessToken")
        )
        val json = JSONObject(response)
        val token = json.optString("nex_token").ifBlank {
            json.optString("nx2")
        }

        require(token.startsWith("nx2.")) {
            "Nextendo did not return a valid nx2 game token."
        }

        val expiresIn = json.optLong("expires_in", 24L * 60L * 60L)
        val expiresAt = System.currentTimeMillis() / 1000L + expiresIn
        return NexGameToken(
            token = token,
            expiresAtEpochSeconds = expiresAt,
            pid = json.optLong("pid", 0L),
            username = json.optString("username"),
            friendCode = json.optString("friend_code")
        )
    }

    private fun parseOAuthTokens(response: String): OAuthTokens {
        val json = JSONObject(response)
        val access = json.optString("access_token")
        val refresh = json.optString("refresh_token")
        val expiresIn = json.optLong("expires_in", 0L)

        require(access.isNotBlank()) { "Nextendo token response did not contain access_token." }
        require(refresh.isNotBlank()) { "Nextendo token response did not contain refresh_token." }

        return OAuthTokens(
            accessToken = access,
            refreshToken = refresh,
            expiresAtEpochSeconds = System.currentTimeMillis() / 1000L + expiresIn
        )
    }

    private fun postForm(url: String, values: Map<String, String>): String {
        val body = values.entries.joinToString("&") { (key, value) ->
            formEncode(key) + "=" + formEncode(value)
        }.toByteArray(StandardCharsets.UTF_8)

        return request(
            url = url,
            method = "POST",
            headers = mapOf("Content-Type" to "application/x-www-form-urlencoded; charset=utf-8"),
            body = body
        )
    }

    private fun request(
        url: String,
        method: String,
        headers: Map<String, String> = emptyMap(),
        body: ByteArray? = null
    ): String {
        val connection = (URL(url).openConnection() as HttpURLConnection)
        try {
            connection.requestMethod = method
            connection.connectTimeout = 15_000
            connection.readTimeout = 20_000
            connection.useCaches = false
            connection.setRequestProperty("Accept", "application/json")
            headers.forEach { (name, value) -> connection.setRequestProperty(name, value) }

            if (body != null) {
                connection.doOutput = true
                connection.outputStream.use { it.write(body) }
            }

            val status = connection.responseCode
            val stream = if (status in 200..299) connection.inputStream else connection.errorStream
            val payload = stream?.use { input ->
                val output = ByteArrayOutputStream()
                input.copyTo(output)
                output.toString("UTF-8")
            }.orEmpty()

            if (status !in 200..299) {
                // Do not include authorization headers or token values in exceptions/logs.
                val safeMessage = try {
                    JSONObject(payload).optString("error_description")
                        .ifBlank { JSONObject(payload).optString("error") }
                } catch (_: Exception) {
                    ""
                }
                throw NextendoException(
                    status,
                    safeMessage.ifBlank { "Nextendo request failed (HTTP $status)." }
                )
            }

            return payload
        } finally {
            connection.disconnect()
        }
    }

    private fun randomBytes(size: Int): ByteArray =
        ByteArray(size).also { SecureRandom().nextBytes(it) }

    private fun base64Url(bytes: ByteArray): String =
        Base64.encodeToString(
            bytes,
            Base64.URL_SAFE or Base64.NO_PADDING or Base64.NO_WRAP
        )

    private fun formEncode(value: String): String =
        URLEncoder.encode(value, "UTF-8")
}
